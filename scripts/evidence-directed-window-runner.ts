// ─── Fixed policy (not operator-overridable) ───────────────────────────────

export const WINDOW_CHAIN_ID = PULSECHAIN_REFERENCE.id;
export const WINDOW_SOURCE_FAMILIES = ["TRANSFERS", "DEX", "LP", "STAKING"] as const;
export const POLICY_LABEL_PREFIX = "EVIDENCE_DIRECTED_WINDOW_V1:";
export const MAX_REASON_SLUG_LENGTH = 64;

// ─── Reason slug / policyLabel (pure) ──────────────────────────────────────

/**
 * Deterministic lowercase [a-z0-9-] slug from an arbitrary operator reason.
 * Returns null when nothing sanitizable remains (empty, punctuation-only,
 * etc.) so the caller can fail closed rather than submit an empty label.
 */
export function slugifyReason(reason: string): string | null {
  const slug = reason
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, MAX_REASON_SLUG_LENGTH)
    .replace(/-$/g, "");
  return slug.length > 0 ? slug : null;
}

export type PolicyLabelResult =
  | { ok: true; policyLabel: string; slug: string }
  | { ok: false; reason: string };

/**
 * Builds the machine-generated, versioned policyLabel from the operator's
 * reason text. The `EVIDENCE_DIRECTED_WINDOW_V1:` prefix is fixed by this
 * function alone — nothing in the CLI layer can substitute or bypass it.
 */
export function buildPolicyLabel(reasonInput: string): PolicyLabelResult {
  const slug = slugifyReason(reasonInput);
  if (!slug) {
    return { ok: false, reason: "reason produced an empty slug after sanitization; provide a reason containing at least one letter or digit" };
  }
  return { ok: true, policyLabel: `${POLICY_LABEL_PREFIX}${slug}`, slug };
}

// ─── Pre-submit validation gates (pure) ────────────────────────────────────

export type GateResult = { ok: true } | { ok: false; reason: string };

export function validateChainId(chainId: number): GateResult {
  if (chainId !== WINDOW_CHAIN_ID) {
    return { ok: false, reason: `chainId must be ${WINDOW_CHAIN_ID} (PulseChain); got ${chainId}` };
  }
  return { ok: true };
}

export function validateBlockOrder(args: { startBlock: bigint; endBlock: bigint }): GateResult {
  if (args.startBlock > args.endBlock) {
    return { ok: false, reason: `startBlock ${args.startBlock} must be less than or equal to endBlock ${args.endBlock}` };
  }
  return { ok: true };
}

export function validateRangeSize(args: {
  startBlock: bigint;
  endBlock: bigint;
  maxBlockSpan?: bigint;
}): GateResult {
  const maxBlockSpan = args.maxBlockSpan ?? MANUAL_SYNC_MAX_BLOCK_SPAN;
  const span = args.endBlock - args.startBlock;
  if (span > maxBlockSpan) {
    return {
      ok: false,
      reason: `block span ${span} exceeds the operator limit of ${maxBlockSpan} blocks (the same limit POST /api/sync/manual enforces); use a smaller range`,
    };
  }
  return { ok: true };
}

/**
 * Mechanical hard stop against planning or submitting a window whose
 * startBlock does not classify as PULSECHAIN_POST_FORK
 * (`classifyPulseChainBlockProvenance`, src/services/chains/fork-provenance.ts).
 * Runs identically in both the dry-run and execute paths.
 */
export function validateForkBoundary(args: { startBlock: bigint }): GateResult {
  const provenance = classifyPulseChainBlockProvenance({
    chainId: WINDOW_CHAIN_ID,
    blockNumber: args.startBlock,
  });
  if (provenance !== "PULSECHAIN_POST_FORK") {
    return {
      ok: false,
      reason: `proposed startBlock ${args.startBlock} classifies as ${provenance}, not PULSECHAIN_POST_FORK; this runner must never plan or submit a window at or below the PulseChain fork boundary (lastInheritedBlock ${PULSECHAIN_FORK_BOUNDARY.lastInheritedBlock})`,
    };
  }
  return { ok: true };
}

export function validateWalletAddress(walletAddress: string): GateResult {
  if (!/^0x[a-fA-F0-9]{40}$/.test(walletAddress)) {
    return { ok: false, reason: `walletAddress must be a valid EVM address; got ${JSON.stringify(walletAddress)}` };
  }
  return { ok: true };
}

export function validateNoActiveOperation(args: { activeRunCount: number }): GateResult {
  if (args.activeRunCount > 0) {
    return {
      ok: false,
      reason: `${args.activeRunCount} active (PENDING/RUNNING) SyncRun(s) exist; refusing to submit while an operation is active`,
    };
  }
  return { ok: true };
}

export function validateNoPolicyLabelCollision(args: {
  policyLabel: string;
  existingPolicyLabels: readonly string[];
}): GateResult {
  if (args.existingPolicyLabels.includes(args.policyLabel)) {
    return { ok: false, reason: `a SyncRun with policyLabel "${args.policyLabel}" already exists` };
  }
  return { ok: true };
}

