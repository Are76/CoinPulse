/**
 * Evidence-directed multi-family historical window runner — operator utility
 * only.
 *
 * Submits ONE explicitly approved, bounded, post-fork PulseChain historical
 * block window through the existing production sync pipeline
 * (`POST /api/sync/manual`) for all four supported source families at once
 * (`TRANSFERS`, `DEX`, `LP`, `STAKING`). It does not implement a new
 * ingestion architecture, does not modify `runWalletSync` or
 * `mergeCursorWindow`, and does not perform reorg detection or portfolio
 * materialization.
 *
 * A historical window submitted here is, by construction, disconnected from
 * the wallet's live SyncCursor for at least one family (that is the entire
 * point — it targets a gap the ordinary forward/backfill cursor has not
 * reached). `mergeCursorWindow` already refuses to move a cursor across a
 * disconnected gap (src/services/sync/sync-state-store.ts), so a successful
 * run here ingests raw + canonical ledger evidence for the window WITHOUT
 * advancing SyncCursor and WITHOUT claiming the wallet's historical coverage
 * is now contiguous. This runner relies on that existing invariant; it does
 * not attempt to force, bypass, or duplicate it.
 *
 * Known limitations this runner does NOT attempt to fix (out of scope):
 *   - Reorg detection (`detectReorgMismatch`, `ReorgEvent`,
 *     `markRawDataRangeReorged`) is not wired into production ingestion.
 *     Re-ingesting a block under a genuinely different blockHash is a
 *     pre-existing correctness gap this runner does not address.
 *   - Portfolio materialization: this runner NEVER calls rebuild or any
 *     equivalent materialization operation. PortfolioTokenBalance may remain
 *     stale relative to a newly ingested window until a separately
 *     authorized rebuild runs.
 *
 * Safety defaults:
 *   - Dry-run unless --execute is passed.
 *   - sourceFamilies is fixed to ["TRANSFERS", "DEX", "LP", "STAKING"] and is
 *     NOT an operator-supplied argument.
 *   - The fork-boundary check (classifyPulseChainBlockProvenance) runs in
 *     BOTH the dry-run and execute paths, before any HTTP call.
 *   - The block span is capped by the existing manual-sync limit
 *     (MANUAL_SYNC_MAX_BLOCK_SPAN, src/services/api/validation.ts) — the same
 *     limit POST /api/sync/manual itself enforces.
 *   - The policyLabel prefix `EVIDENCE_DIRECTED_WINDOW_V1:` is generated by
 *     the runner from the operator's `--reason`; the operator cannot type or
 *     override the prefix.
 *
 * Usage (dry-run, the safe default):
 *   npx tsx --conditions react-server scripts/evidence-directed-window-runner.ts \
 *     --wallet-address 0x... --chain-id 369 \
 *     --start-block 17233000 --end-block 17233999 \
 *     --reason "recover window 65 evidence"
 *
 * Usage (execute exactly one window):
 *   npx tsx --conditions react-server scripts/evidence-directed-window-runner.ts \
 *     --execute --wallet-address 0x... --chain-id 369 \
 *     --start-block 17233000 --end-block 17233999 \
 *     --reason "recover window 65 evidence"
 *
 * Required environment variables:
 *   DATABASE_URL  PostgreSQL connection string (direct read-only planning
 *                 queries; all mutations happen through the HTTP route)
 *   REDIS_URL     Redis connection string (required by server-env)
 *
 * The --conditions react-server flag is required because imported ingestion
 * service modules use the server-only guard, which is a no-op only under
 * that export condition.
 *
 * Exit behaviour:
 *   - Exits 0 on any clean stop (dry-run completion, execute completion,
 *     or a gate failure reported through the JSON summary).
 *   - Exits 1 on invalid arguments, missing environment, HTTP submission
 *     failure, poll timeout, or an unterminated/failed SyncRun.
 *   - Never prints DATABASE_URL, REDIS_URL, RPC URLs, secrets, or headers.
 */

