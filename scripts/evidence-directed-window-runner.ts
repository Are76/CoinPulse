// ─── Evidence records ───────────────────────────────────────────────────────

export type EvidenceRecord = {
  kind: "dry-run" | "execute" | "stop";
  at: string;
  [key: string]: unknown;
};

/** JSON.stringify replacer that serializes bigint as a decimal string. */
function bigintSafeReplacer(_key: string, value: unknown) {
  return typeof value === "bigint" ? value.toString() : value;
}

export function serializeEvidence(record: EvidenceRecord): string {
  return JSON.stringify(record, bigintSafeReplacer);
}

export async function writeEvidenceLine(evidenceDir: string, record: EvidenceRecord): Promise<void> {
  await mkdir(evidenceDir, { recursive: true });
  const filePath = path.join(evidenceDir, "evidence-directed-window-evidence.jsonl");
  await appendFile(filePath, `${serializeEvidence(record)}\n`, "utf8");
}

// ─── Runner DB client (narrow, injectable) ─────────────────────────────────

export type RunnerSyncRunRecord = {
  id: string;
  trigger: string;
  status: string;
  stage: string;
  sourceFamilies: readonly string[];
  startBlock: bigint | null;
  endBlock: bigint | null;
  warningCount: number;
  warningDetails: unknown;
  errorMessage: string | null;
  failedSourceFamily: string | null;
  failedFromBlock: bigint | null;
  failedToBlock: bigint | null;
};

export type RunnerDbClient = {
  syncCursor: {
    findUnique: (args: unknown) => Promise<{
      fromBlock: bigint;
      toBlock: bigint;
      blockHash: string | null;
    } | null>;
  };
  syncRun: {
    findMany: (args: unknown) => Promise<Array<{ policyLabel: string }>>;
    findUnique: (args: unknown) => Promise<RunnerSyncRunRecord | null>;
    count: (args: unknown) => Promise<number>;
  };
};

export async function getCursorForFamily(
  db: RunnerDbClient,
  args: { walletId: string; chainId: number; sourceFamily: (typeof WINDOW_SOURCE_FAMILIES)[number] },
): Promise<CursorSnapshot> {
  const cursor = await db.syncCursor.findUnique({
    where: {
      walletId_chainId_sourceFamily: {
        walletId: args.walletId,
        chainId: args.chainId,
        sourceFamily: args.sourceFamily,
      },
    },
    select: { fromBlock: true, toBlock: true, blockHash: true },
  });
  return cursor ? { fromBlock: cursor.fromBlock, toBlock: cursor.toBlock } : null;
}

export async function getCursorsForAllFamilies(
  db: RunnerDbClient,
  args: { walletId: string; chainId: number },
): Promise<Record<(typeof WINDOW_SOURCE_FAMILIES)[number], CursorSnapshot>> {
  const entries = await Promise.all(
    WINDOW_SOURCE_FAMILIES.map(async (sourceFamily) => [
      sourceFamily,
      await getCursorForFamily(db, { walletId: args.walletId, chainId: args.chainId, sourceFamily }),
    ] as const),
  );
  return Object.fromEntries(entries) as Record<(typeof WINDOW_SOURCE_FAMILIES)[number], CursorSnapshot>;
}

export async function listActivePolicyLabels(db: RunnerDbClient, chainId: number): Promise<string[]> {
  const runs = await db.syncRun.findMany({ where: { chainId }, select: { policyLabel: true } });
  return runs.map((r) => r.policyLabel);
}

export async function countActiveOperations(db: RunnerDbClient): Promise<number> {
  return db.syncRun.count({ where: { status: { in: ["PENDING", "RUNNING"] } } });
}

// ─── HTTP + polling ─────────────────────────────────────────────────────────

export type HttpResponse = { status: number; body: unknown };
export type HttpPost = (url: string, body: unknown) => Promise<HttpResponse>;
export type HttpGet = (url: string) => Promise<HttpResponse>;

export async function checkServerHealth(httpGet: HttpGet, baseUrl: string): Promise<GateResult> {
  let response: HttpResponse;
  try {
    response = await httpGet(`${baseUrl}/api/debug/health`);
  } catch (err) {
    return { ok: false, reason: `health check request failed: ${err instanceof Error ? err.message : String(err)}` };
  }
  const body = response.body as { data?: { status?: string } } | undefined;
  if (response.status !== 200 || body?.data?.status !== "ok") {
    return { ok: false, reason: `server health check did not report ok (status ${response.status})` };
  }
  return { ok: true };
}

export async function pollSyncRunToTerminal(
  db: RunnerDbClient,
  runId: string,
  deps: { now: () => Date; sleep: (ms: number) => Promise<void>; pollIntervalMs: number; pollTimeoutMs: number },
): Promise<{ ok: true; run: RunnerSyncRunRecord } | { ok: false; reason: "timeout"; lastRun: RunnerSyncRunRecord | null }> {
  const deadline = deps.now().getTime() + deps.pollTimeoutMs;

  for (;;) {
    const run = await db.syncRun.findUnique({ where: { id: runId } });
    if (run && (run.status === "COMPLETED" || run.status === "FAILED")) {
      return { ok: true, run };
    }
    if (deps.now().getTime() >= deadline) {
      return { ok: false, reason: "timeout", lastRun: run };
    }
    await deps.sleep(deps.pollIntervalMs);
  }
}

// ─── Orchestrator ───────────────────────────────────────────────────────────

export type RunnerDeps = {
  db: RunnerDbClient;
  resolveWallet: (args: { walletAddress: string; chainId: number }) => Promise<{ id: string; address: string } | null>;
  httpGet: HttpGet;
  httpPost: HttpPost;
  now: () => Date;
  sleep: (ms: number) => Promise<void>;
  writeEvidence: (record: EvidenceRecord) => Promise<void>;
};

export type RunnerSummary = {
  mode: "dry-run" | "execute";
  stoppedReason: string;
  detail?: string;
};

const REORG_LIMITATION_DISCLOSURE =
  "Reorg detection (detectReorgMismatch, ReorgEvent, markRawDataRangeReorged) is NOT wired into production ingestion. This runner does not detect or guard against re-ingesting a block under a different blockHash than a prior observation.";

const MATERIALIZATION_LIMITATION_DISCLOSURE =
  "This runner never calls rebuild or any portfolio materialization operation. Canonical ledger ingestion for this window may complete while PortfolioTokenBalance remains stale relative to it. A separate, explicitly authorized rebuild is required to refresh portfolio totals.";

export async function runEvidenceDirectedWindowRunner(
  options: RunnerCliOptions,
  deps: RunnerDeps,
): Promise<RunnerSummary> {
  const mode: "dry-run" | "execute" = options.execute ? "execute" : "dry-run";

  const chainIdGate = validateChainId(options.chainId);
  if (!chainIdGate.ok) return stop(deps, mode, "invalid_chain_id", chainIdGate.reason);

  const orderGate = validateBlockOrder({ startBlock: options.startBlock, endBlock: options.endBlock });
  if (!orderGate.ok) return stop(deps, mode, "invalid_block_order", orderGate.reason);

  const rangeGate = validateRangeSize({ startBlock: options.startBlock, endBlock: options.endBlock });
  if (!rangeGate.ok) return stop(deps, mode, "range_too_large", rangeGate.reason);

  // Fork-boundary check: applies identically in both dry-run and execute
  // paths, before any evidence is written or HTTP call made.
  const forkGate = validateForkBoundary({ startBlock: options.startBlock });
  if (!forkGate.ok) return stop(deps, mode, "fork_boundary_violation", forkGate.reason);

  const policyLabelResult = buildPolicyLabel(options.reason);
  if (!policyLabelResult.ok) return stop(deps, mode, "invalid_reason", policyLabelResult.reason);
  const { policyLabel } = policyLabelResult;

  const wallet = await deps.resolveWallet({ walletAddress: options.walletAddress, chainId: options.chainId });
  if (!wallet) return stop(deps, mode, "wallet_not_found");

  const cursorsBefore = await getCursorsForAllFamilies(deps.db, { walletId: wallet.id, chainId: options.chainId });

  if (mode === "dry-run") {
    const disconnection = Object.fromEntries(
      WINDOW_SOURCE_FAMILIES.map((sourceFamily) => [
        sourceFamily,
        classifyCursorDisconnection({
          cursor: cursorsBefore[sourceFamily],
          startBlock: options.startBlock,
          endBlock: options.endBlock,
        }),
      ]),
    );

    await deps.writeEvidence({
      kind: "dry-run",
      at: deps.now().toISOString(),
      mode: "dry-run",
      wallet: { chainId: options.chainId, address: options.walletAddress },
      requestedRange: { startBlock: options.startBlock.toString(), endBlock: options.endBlock.toString() },
      sourceFamilies: [...WINDOW_SOURCE_FAMILIES],
      policyLabel,
      forkClassification: "PULSECHAIN_POST_FORK",
      cursorsBefore: serializeCursors(cursorsBefore),
      disconnectionFromExistingCoverage: disconnection,
      executed: false,
    });

    return { mode, stoppedReason: "dry_run_reported" };
  }

  // ── Execute path ──
  const activeRunCount = await countActiveOperations(deps.db);
  const activeOpGate = validateNoActiveOperation({ activeRunCount });
  if (!activeOpGate.ok) return stop(deps, mode, "active_operation_conflict", activeOpGate.reason);

  const existingLabels = await listActivePolicyLabels(deps.db, options.chainId);
  const labelGate = validateNoPolicyLabelCollision({ policyLabel, existingPolicyLabels: existingLabels });
  if (!labelGate.ok) return stop(deps, mode, "policy_label_collision", labelGate.reason);

  const healthGate = await checkServerHealth(deps.httpGet, options.baseUrl);
  if (!healthGate.ok) return stop(deps, mode, "server_unhealthy", healthGate.reason);

  const submittedAt = deps.now().toISOString();
  const requestBody = buildManualSyncRequestBody({
    walletAddress: options.walletAddress,
    startBlock: options.startBlock,
    endBlock: options.endBlock,
    policyLabel,
  });
  const postResponse = await deps.httpPost(`${options.baseUrl}/api/sync/manual`, requestBody);
  const runId = (postResponse.body as { data?: { runId?: string } } | undefined)?.data?.runId;
  if (postResponse.status !== 202 || !runId) {
    await deps.writeEvidence({
      kind: "stop",
      at: deps.now().toISOString(),
      mode,
      reason: "manual_sync_submit_failed",
      detail: `POST /api/sync/manual returned status ${postResponse.status}`,
      policyLabel,
      submittedAt,
    });
    return { mode, stoppedReason: "manual_sync_submit_failed", detail: `POST /api/sync/manual returned status ${postResponse.status}` };
  }

  const polled = await pollSyncRunToTerminal(deps.db, runId, {
    now: deps.now,
    sleep: deps.sleep,
    pollIntervalMs: options.pollIntervalMs,
    pollTimeoutMs: options.pollTimeoutMs,
  });
  if (!polled.ok) {
    await deps.writeEvidence({
      kind: "stop",
      at: deps.now().toISOString(),
      mode,
      reason: "poll_timeout",
      detail: `SyncRun ${runId} did not reach a terminal state within ${options.pollTimeoutMs}ms`,
      policyLabel,
      runId,
      submittedAt,
    });
    return { mode, stoppedReason: "poll_timeout", detail: `SyncRun ${runId} did not reach a terminal state within ${options.pollTimeoutMs}ms` };
  }
  const terminalAt = deps.now().toISOString();

  const cursorsAfter = await getCursorsForAllFamilies(deps.db, { walletId: wallet.id, chainId: options.chainId });
  const cursorComparison = Object.fromEntries(
    WINDOW_SOURCE_FAMILIES.map((sourceFamily) => [
      sourceFamily,
      {
        before: cursorsBefore[sourceFamily],
        after: cursorsAfter[sourceFamily],
        unchanged: cursorsIdentical(cursorsBefore[sourceFamily], cursorsAfter[sourceFamily]),
      },
    ]),
  );

  const terminalStatus = polled.run.status;
  const succeeded = terminalStatus === "COMPLETED";

  await deps.writeEvidence({
    kind: "execute",
    at: terminalAt,
    mode: "execute",
    wallet: { chainId: options.chainId, address: options.walletAddress },
    submittedRange: { startBlock: options.startBlock.toString(), endBlock: options.endBlock.toString() },
    sourceFamilies: [...WINDOW_SOURCE_FAMILIES],
    policyLabel,
    runId,
    submittedAt,
    terminalAt,
    terminalStatus,
    warningCount: polled.run.warningCount,
    warningDetails: polled.run.warningDetails,
    errorMessage: polled.run.errorMessage,
    cursorComparison: serializeCursorComparison(cursorComparison),
    reorgLimitation: REORG_LIMITATION_DISCLOSURE,
    materializationLimitation: MATERIALIZATION_LIMITATION_DISCLOSURE,
    portfolioTotalsRefreshed: false,
  });

  return {
    mode,
    stoppedReason: succeeded ? "execute_completed" : "sync_run_not_completed",
    detail: succeeded ? undefined : `SyncRun ${runId} terminal status was ${terminalStatus}, not COMPLETED`,
  };
}

function serializeCursors(cursors: Record<string, CursorSnapshot>) {
  return Object.fromEntries(
    Object.entries(cursors).map(([family, cursor]) => [
      family,
      cursor ? { fromBlock: cursor.fromBlock.toString(), toBlock: cursor.toBlock.toString() } : null,
    ]),
  );
}

function serializeCursorComparison(
  comparison: Record<string, { before: CursorSnapshot; after: CursorSnapshot; unchanged: boolean }>,
) {
  return Object.fromEntries(
    Object.entries(comparison).map(([family, entry]) => [
      family,
      {
        before: entry.before ? { fromBlock: entry.before.fromBlock.toString(), toBlock: entry.before.toBlock.toString() } : null,
        after: entry.after ? { fromBlock: entry.after.fromBlock.toString(), toBlock: entry.after.toBlock.toString() } : null,
        unchanged: entry.unchanged,
      },
    ]),
  );
}

async function stop(
  deps: RunnerDeps,
  mode: "dry-run" | "execute",
  reason: string,
  detail?: string,
): Promise<RunnerSummary> {
  await deps.writeEvidence({ kind: "stop", at: deps.now().toISOString(), mode, reason, detail });
  return { mode, stoppedReason: reason, detail };
}

// ─── CLI entrypoint ─────────────────────────────────────────────────────────

function safeStringify(value: unknown): string {
  return JSON.stringify(value, bigintSafeReplacer, 2);
}

const SUCCESSFUL_STOP_REASONS = new Set(["dry_run_reported", "execute_completed"]);

async function main(): Promise<void> {
  const parsed = parseRunnerCliArgs(process.argv.slice(2));
  if (!parsed.ok) {
    console.error(`evidence-directed-window-runner: ${parsed.error}`);
    console.error(RUNNER_CLI_USAGE);
    process.exitCode = 1;
    return;
  }

  const envCheck = checkEnv(process.env as Record<string, string | undefined>);
  if (!envCheck.ok) {
    console.error(
      `evidence-directed-window-runner: missing required environment variables: ${envCheck.missing.join(", ")}`,
    );
    process.exitCode = 1;
    return;
  }

  // Deferred imports so argument/env validation always runs first and the
  // server-only service modules never load for an invalid invocation.
  const { PrismaClient } = await import("@prisma/client");
  const { createPrismaAdapter } = await import("@/lib/prisma-adapter");
  const { resolveTrackedWalletByAddress } = await import("@/services/api/wallets");

  const prisma = new PrismaClient({ adapter: createPrismaAdapter() });

  const deps: RunnerDeps = {
    db: prisma as unknown as RunnerDbClient,
    resolveWallet: resolveTrackedWalletByAddress,
    httpGet: async (url) => {
      const res = await fetch(url);
      return { status: res.status, body: await res.json().catch(() => undefined) };
    },
    httpPost: async (url, body) => {
      const res = await fetch(url, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify(body),
      });
      return { status: res.status, body: await res.json().catch(() => undefined) };
    },
    now: () => new Date(),
    sleep: (ms) => new Promise((resolve) => setTimeout(resolve, ms)),
    writeEvidence: (record) => writeEvidenceLine(parsed.options.evidenceDir, record),
  };

  try {
    const summary = await runEvidenceDirectedWindowRunner(parsed.options, deps);
    console.log(safeStringify(summary));
    if (!SUCCESSFUL_STOP_REASONS.has(summary.stoppedReason)) {
      process.exitCode = 1;
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    console.error(`evidence-directed-window-runner error: ${message}`);
    process.exitCode = 1;
  } finally {
    await prisma.$disconnect();
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    const message = err instanceof Error ? err.message : String(err);
    console.error(`evidence-directed-window-runner error: ${message}`);
    process.exitCode = 1;
  });
}
